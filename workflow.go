package github

import (
	"bytes"
	"os"
	"path/filepath"

	"webtyp.com/deploy"
	"webtyp.com/ghaction"
)

const (
	workflowDir      = ".github/workflows"
	workflowFileName = "deploy.yml"
	workflowRelPath  = ".github/workflows/deploy.yml"
	workflowGitRef   = "origin/main:.github/workflows/deploy.yml"
	workflowName     = "Deploy"
	workflowJobName  = "deploy"
	defaultBranch    = "main"
	permContents     = "contents"
	permRead         = "read"
	workflowHeader   = "# GENERATED by webtyp from config/deploy.go — do not edit. Change config/deploy.go and run Provision from the webtyp DEPLOY tab.\n"
)

func render(p deploy.Plan, job deploy.Job) []byte {
	var env []ghaction.KeyValue
	for _, s := range job.Secrets {
		env = append(env, ghaction.KeyValue{Key: s, Value: "${{ secrets." + s + " }}"})
	}

	var with []ghaction.KeyValue
	for _, kv := range job.With {
		with = append(with, ghaction.KeyValue{Key: kv.Name, Value: kv.Value})
	}

	w := ghaction.Workflow{
		Name: workflowName,
		On: ghaction.On{
			Push:             &ghaction.Push{Branches: []string{defaultBranch}},
			WorkflowDispatch: &ghaction.WorkflowDispatch{},
		},
		Permissions: map[string]string{
			permContents: permRead,
		},
		Jobs: map[string]ghaction.Job{
			workflowJobName: {
				RunsOn: ghaction.DefaultRunsOn,
				Env:    env,
				Steps: []ghaction.WorkflowStep{
					ghaction.CheckoutStep(),
					{
						Uses: job.Uses,
						With: with,
					},
				},
			},
		},
	}

	return append([]byte(workflowHeader), w.Render()...)
}

func (c *CI) Provision(p deploy.Plan, job deploy.Job) error {
	path := filepath.Join(c.rootDir, workflowDir, workflowFileName)
	content := render(p, job)

	existing, err := os.ReadFile(path)
	if err == nil && bytes.Equal(existing, content) {
		return nil
	}

	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	return os.WriteFile(path, content, 0644)
}

